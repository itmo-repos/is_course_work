package ru.ifmo.is.backend.entities.enums;

public enum RoleCode {
    CURATOR,  // курирующий сотрудник: отвечает за процессы приема, размещения и отгрузки партий
    ENGINEER, // штатный инженер: отвечает за климатическое оборудование, мониторинг и обслуживание системы
    SECURITY, // сотрудник охраны: обеспечивает пропускной режим, ведение журналов доступа и безопасность
    ADMIN     // администратор системы: обладает наивысшими правами, управляет ролями, сотрудниками и отчетностью
}
